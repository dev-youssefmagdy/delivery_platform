<?php

namespace App\Http\Controllers\Admin\Demo;

use App\DataTables\Admin\Demo\DemoItemsDataTable;
use App\DTOs\Demo\DemoItemData;
use App\DTOs\Demo\DemoItemFilterData;
use App\Http\Controllers\Admin\AdminController;
use App\Http\Requests\Admin\Demo\ArchiveDemoItemRequest;
use App\Http\Requests\Admin\Demo\DestroyDemoItemRequest;
use App\Http\Requests\Admin\Demo\StoreDemoItemRequest;
use App\Http\Requests\Admin\Demo\UpdateDemoItemRequest;
use App\Models\DemoItem;
use App\Services\Admin\AdminExportService;
use App\Services\Audit\AuditTrailService;
use App\Services\Demo\DemoItemService;
use App\Support\Http\AdminFormResponse;
use Illuminate\Contracts\View\View;
use Illuminate\Http\Request;

/**
 * Demo Item proof module (P0.3, local/testing only). Generated by make:admin-module, then extended to
 * exercise every admin component: quick-create modal, drawer quick view, archive with mandatory reason.
 */
final class DemoItemController extends AdminController
{
    public function __construct(private readonly DemoItemService $service) {}

    public function index(DemoItemsDataTable $table): mixed
    {
        return $table->render('admin.demo-items.index', ['stats' => $this->service->stats()]);
    }

    public function create(): View
    {
        return view('admin.demo-items.create');
    }

    public function store(StoreDemoItemRequest $request): AdminFormResponse
    {
        $demoItem = $this->service->create(DemoItemData::fromRequest($request), $this->actor());
        $response = $this->formResponse(__('admin.demo_items.created'));

        // Quick-create modal: stay on the listing; full form: go to the record.
        return $request->boolean('quick')
            ? $response->closeModal()->reset()->reloadTable(DemoItemsDataTable::TABLE_ID)
            : $response->redirect(route('admin.demo-items.show', $demoItem));
    }

    public function show(DemoItem $demoItem): View
    {
        return view('admin.demo-items.show', ['details' => $this->service->details($demoItem)]);
    }

    public function quickView(DemoItem $demoItem): View
    {
        return view('admin.demo-items._quick-view', ['details' => $this->service->details($demoItem)]);
    }

    public function activity(DemoItem $demoItem, AuditTrailService $trail): View
    {
        return view('admin.partials.activity', ['logs' => $trail->latestFor($demoItem)]);
    }

    public function edit(DemoItem $demoItem): View
    {
        return view('admin.demo-items.edit', ['details' => $this->service->details($demoItem)]);
    }

    public function update(UpdateDemoItemRequest $request, DemoItem $demoItem): AdminFormResponse
    {
        $this->service->update($demoItem, DemoItemData::fromRequest($request), $this->actor());

        return $this->formResponse(__('admin.demo_items.updated'))->redirect(route('admin.demo-items.show', $demoItem));
    }

    public function archive(ArchiveDemoItemRequest $request, DemoItem $demoItem): AdminFormResponse
    {
        $this->service->archive($demoItem, $request->reason(), $this->actor());

        $response = $this->formResponse(__('admin.demo_items.archived'))->reloadTable(DemoItemsDataTable::TABLE_ID);

        return $request->boolean('from_show') ? $response->reload() : $response;
    }

    public function destroy(DestroyDemoItemRequest $request, DemoItem $demoItem): AdminFormResponse
    {
        $this->service->delete($demoItem, $this->actor(), $request->reason());

        $response = $this->formResponse(__('admin.demo_items.deleted'))->reloadTable(DemoItemsDataTable::TABLE_ID);

        return $request->boolean('from_show') ? $response->redirect(route('admin.demo-items.index')) : $response;
    }

    public function export(Request $request, DemoItemsDataTable $table, AdminExportService $exports): AdminFormResponse
    {
        $export = $exports->queue($table, DemoItemFilterData::fromRequest($request)->toArray(), $this->actor());

        return $this->formResponse(__('admin.exports.queued'))->with('status_url', route('admin.exports.show', $export));
    }
}
