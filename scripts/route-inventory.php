<?php

/*
| Route inventory and authorization audit (P6.1). Not a test suite: reads `php artisan route:list --json` and prints a Markdown report,
| exiting 1 when a non-public route lacks authentication or authorization.
|
|   cd backend && php artisan route:list --json | php ../scripts/route-inventory.php > ../docs/ROUTE_INVENTORY.md
|
| Rules: API routes behind auth:sanctum need a token ability (`ability:` / `abilities:`); admin routes need `auth:admin` plus `can:` (policy)
| or an explicit `admin.access:self|public` marker; everything else is listed as public (website, webhooks, catalogue, health).
*/

$routes = json_decode((string) stream_get_contents(STDIN), true);

if (! is_array($routes)) {
    fwrite(STDERR, "Expected route:list --json on stdin\n");
    exit(2);
}

$short = static fn (string $m): string => preg_replace('~^(?:[\w]+\\\\)+~', '', $m);
$rows = ['api' => [], 'admin' => [], 'public' => []];
$violations = [];

foreach ($routes as $route) {
    if (($route['method'] ?? '') === 'HEAD' || str_starts_with($route['uri'], '_boost') || str_starts_with($route['uri'], 'storage/')) {
        continue;
    }

    $mw = array_map('strval', $route['middleware'] ?? []);
    $flat = implode(',', $mw);
    $method = str_replace('|HEAD', '', $route['method']);
    $uri = '/'.$route['uri'];
    $auth = $ability = $can = $marker = null;
    $throttle = '';

    foreach ($mw as $item) {
        if (preg_match('~^(?:.*\\\\)?Authenticate:(\w+)$|^auth:(\w+)$~', $item, $g) === 1) {
            $auth = $g[1] !== '' ? $g[1] : ($g[2] ?? null);
        } elseif (preg_match('~(?:CheckForAnyAbility|CheckAbilities):(.+)$|^abilit(?:y|ies):(.+)$~', $item, $g) === 1) {
            $ability = $g[1] !== '' ? $g[1] : $g[2];
        } elseif (preg_match('~(?:Authorize|^can):(.+)$~', $item, $g) === 1) {
            $can = $g[1];
        } elseif (preg_match('~(?:DeclareAdminAccess|^admin\.access):(\w+)$~', $item, $g) === 1) {
            $marker = $g[1];
        } elseif (preg_match('~ThrottleRequests:(.+)$~', $item, $g) === 1) {
            $throttle = $g[1];
        }
    }

    $idem = str_contains($flat, 'Idempotency') ? 'yes' : '';
    $signed = str_contains($flat, 'ValidateSignature') ? 'signed' : '';
    $active = str_contains($flat, 'EnsureAccountActive') ? 'yes' : '';

    if (str_starts_with($uri, '/api/')) {
        if ($auth === null) {
            $rows['public'][] = [$method, $uri, $signed ?: ($throttle ? "throttle {$throttle}" : 'open')];
        } else {
            $rows['api'][] = [$method, $uri, $ability ?? '-', $active, $idem, $throttle, $signed];

            if ($ability === null) {
                $violations[] = "API {$method} {$uri}: authenticated but no token ability";
            }
        }
    } elseif (str_starts_with($uri, '/admin')) {
        $kind = $marker ?? ($can !== null ? 'can' : '-');
        $rows['admin'][] = [$method, $uri, $auth ?? '-', $can ?? ($marker ? "admin.access:{$marker}" : '-'), $signed];

        if ($marker !== 'public' && ($auth === null || ($can === null && $marker !== 'self'))) {
            $violations[] = "ADMIN {$method} {$uri}: missing auth:admin or can:/admin.access marker";
        }
    } else {
        $rows['public'][] = [$method, $uri, $signed ?: ($throttle ? "throttle {$throttle}" : 'open')];
    }
}

$table = static function (array $head, array $data): string {
    $out = '| '.implode(' | ', $head)." |\n|".str_repeat(' --- |', count($head))."\n";

    foreach ($data as $row) {
        $out .= '| '.implode(' | ', array_map(static fn ($c) => str_replace('|', '\\|', (string) $c), $row))." |\n";
    }

    return $out;
};

echo "# Route inventory\n\nGenerated by `scripts/route-inventory.php` from `php artisan route:list --json`.\n\n";
printf("Totals: %d API routes behind a token, %d admin routes, %d public routes (website, catalogue, webhook, health).\n\n", count($rows['api']), count($rows['admin']), count($rows['public']));
echo "## API (auth:sanctum + ability)\n\n".$table(['Method', 'URI', 'Ability (any of)', 'Active account', 'Idempotency-Key', 'Throttle', 'Signed'], $rows['api']);

$groups = [];

foreach ($rows['admin'] as $r) {
    $parts = explode('/', trim($r[1], '/'));
    $groups[$parts[1] ?? 'home'][] = $r;
}

ksort($groups);
echo "\n## Admin (auth:admin + can: / admin.access marker), by module\n\n| Module | Routes | With can: | self | public |\n| --- | --- | --- | --- | --- |\n";

foreach ($groups as $name => $list) {
    $can = count(array_filter($list, static fn ($r) => ! str_starts_with($r[3], 'admin.access') && $r[3] !== '-'));
    $self = count(array_filter($list, static fn ($r) => $r[3] === 'admin.access:self'));
    $public = count(array_filter($list, static fn ($r) => $r[3] === 'admin.access:public'));
    echo "| {$name} | ".count($list)." | {$can} | {$self} | {$public} |\n";
}

echo "\n## Public routes\n\n".$table(['Method', 'URI', 'Protection'], $rows['public']);

if ($violations !== []) {
    fwrite(STDERR, "VIOLATIONS:\n".implode("\n", $violations)."\n");
    exit(1);
}

fwrite(STDERR, "OK: no authorization gaps.\n");
