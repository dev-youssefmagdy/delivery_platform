<?php

namespace Tests\Feature\Admin\Demo;

use App\DataTables\Admin\Demo\DemoItemsDataTable;
use App\Enums\Admin\AdminPermission;
use App\Enums\Common\AuditAction;
use App\Enums\Demo\DemoItemStatus;
use App\Enums\Demo\DemoItemType;
use App\Jobs\Admin\GenerateAdminExport;
use App\Models\AdminAuditLog;
use App\Models\AdminExport;
use App\Models\DemoItem;
use Database\Seeders\CurrencySeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Queue;
use Tests\Concerns\InteractsWithAdmin;
use Tests\TestCase;

/**
 * Admin Module Contract (Plan §5.6) for DemoItem — generated by make:admin-module (payload extended for the demo fields).
 */
class DemoItemAdminTest extends TestCase
{
    use InteractsWithAdmin;
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();

        $this->seed(CurrencySeeder::class);
    }

    public function test_guests_are_blocked(): void
    {
        $this->assertGuestBlocked($this->get(route('admin.demo-items.index')));
    }

    public function test_admin_without_permission_gets_403_on_page_json_and_datatable(): void
    {
        $this->actingAsAdmin();
        $demoItem = DemoItem::factory()->create();

        $this->get(route('admin.demo-items.index'))->assertForbidden();
        $this->getJson(route('admin.demo-items.show', $demoItem))->assertForbidden()->assertJsonPath('errors._code', 'forbidden');
        $this->datatable(route('admin.demo-items.index'))->assertForbidden();
        $this->postJson(route('admin.demo-items.store'), $this->validPayload())->assertForbidden();
    }

    public function test_index_renders_the_listing_with_a_collapsed_filters_card(): void
    {
        $this->actingAsAdmin([AdminPermission::DemoItemsView]);

        $this->get(route('admin.demo-items.index'))
            ->assertOk()
            ->assertSee('data-filters-for="'.DemoItemsDataTable::TABLE_ID.'"', false)
            ->assertSee('id="'.DemoItemsDataTable::TABLE_ID.'"', false)
            ->assertDontSee(route('admin.demo-items.create'));
    }

    public function test_datatable_json_respects_filters(): void
    {
        $this->actingAsAdmin([AdminPermission::DemoItemsView]);
        $match = DemoItem::factory()->create(['name' => ['ar' => 'Needle عنصر', 'en' => 'Needle item']]);
        DemoItem::factory()->create(['name' => ['ar' => 'آخر', 'en' => 'Other']]);

        $this->datatable(route('admin.demo-items.index'))->assertOk()->assertJsonPath('recordsTotal', 2);

        $this->datatable(route('admin.demo-items.index'), ['search' => 'Needle'])
            ->assertOk()
            ->assertJsonPath('recordsFiltered', 1)
            ->assertJsonPath('data.0.id', $match->id);

        $this->datatable(route('admin.demo-items.index'), ['statuses' => [DemoItemStatus::Draft->value]])
            ->assertOk()
            ->assertJsonPath('recordsFiltered', 2);

        $this->datatable(route('admin.demo-items.index'), ['created_at' => ['from' => now()->addDay()->toDateString()]])
            ->assertOk()
            ->assertJsonPath('recordsFiltered', 0);
    }

    public function test_precognitive_store_validates_without_persisting(): void
    {
        $this->actingAsAdmin([AdminPermission::DemoItemsManage]);

        $this->precognitive('POST', route('admin.demo-items.store'), [])
            ->assertStatus(422)
            ->assertJsonPath('errors._code', 'validation_failed')
            ->assertJsonValidationErrors(['name.ar', 'status']);

        $this->precognitive('POST', route('admin.demo-items.store'), $this->validPayload())
            ->assertNoContent()
            ->assertHeader('Precognition-Success', 'true');

        $this->assertDatabaseCount('demo_items', 0);
    }

    public function test_store_persists_and_writes_an_audit_row(): void
    {
        $this->actingAsAdmin([AdminPermission::DemoItemsManage]);

        $response = $this->postJson(route('admin.demo-items.store'), $this->validPayload())->assertOk()->assertJsonPath('success', true);

        $demoItem = DemoItem::query()->sole();
        $response->assertJsonPath('data.redirect', route('admin.demo-items.show', $demoItem));
        $this->assertDatabaseHas('admin_audit_logs', ['action' => AuditAction::Created->value, 'auditable_type' => 'demo_item', 'auditable_id' => (string) $demoItem->id]);
    }

    public function test_update_writes_an_audit_row_and_rejects_a_stale_lock_version(): void
    {
        $this->actingAsAdmin([AdminPermission::DemoItemsManage]);
        $demoItem = DemoItem::factory()->create();

        $this->putJson(route('admin.demo-items.update', $demoItem), $this->validPayload() + ['lock_version' => 0])->assertOk();
        $this->assertSame(1, $demoItem->refresh()->lock_version);
        $this->assertTrue(AdminAuditLog::query()->where('action', AuditAction::Updated->value)->where('auditable_id', (string) $demoItem->id)->exists());

        $this->putJson(route('admin.demo-items.update', $demoItem), $this->validPayload() + ['lock_version' => 0])
            ->assertStatus(409)
            ->assertJsonPath('errors._code', 'stale_version');
    }

    public function test_delete_writes_an_audit_row(): void
    {
        $this->actingAsAdmin([AdminPermission::DemoItemsManage]);
        $demoItem = DemoItem::factory()->create();

        $this->deleteJson(route('admin.demo-items.destroy', $demoItem))->assertOk()->assertJsonPath('data.reload_table', [DemoItemsDataTable::TABLE_ID]);

        $this->assertModelMissing($demoItem);
        $this->assertDatabaseHas('admin_audit_logs', ['action' => AuditAction::Deleted->value, 'auditable_id' => (string) $demoItem->id]);
    }

    public function test_export_requires_permission_is_queued_and_audited(): void
    {
        Queue::fake();
        $this->actingAsAdmin([AdminPermission::DemoItemsView]);
        $this->postJson(route('admin.demo-items.export'))->assertForbidden();

        $this->actingAsAdmin([AdminPermission::DemoItemsView, AdminPermission::DemoItemsExport]);
        $this->postJson(route('admin.demo-items.export'), ['filters' => ['search' => 'Needle']])->assertOk();

        $export = AdminExport::query()->sole();
        $this->assertSame(['search' => 'Needle'], $export->filters);
        Queue::assertPushed(GenerateAdminExport::class);
        $this->assertDatabaseHas('admin_audit_logs', ['action' => AuditAction::Exported->value, 'auditable_type' => 'admin_export']);
    }

    /**
     * @return array<string, mixed>
     */
    private function validPayload(): array
    {
        return [
            'name' => ['ar' => 'قيمة تجريبية', 'en' => 'Sample value'],
            'code' => 'SAMPLE-1',
            'type' => DemoItemType::Standard->value,
            'price' => 1250,
            'status' => DemoItemStatus::Draft->value,
        ];
    }
}
